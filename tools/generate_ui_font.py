"""Build the Notebook UI's flash-resident, 4-bit alpha Noto Sans SC subset.

Only glyph bitmap data is emitted; no runtime font library is required.
Requires Pillow, and optionally fontTools for validating character coverage.
"""
from __future__ import annotations

import argparse
import ast
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SIZES = (13, 16, 18, 20, 24, 26)
DEFAULT_TEXT = "自然手帐首页今天日记时光收藏设置早上好下午晚上一起记录生活我的小花园晴天阴雨天温度星期一二三四五六年月日返回保存取消完成暂无内容新的开始点击进入当前页面待连接触摸校准"


def source_characters(paths: list[Path]) -> str:
    chars = set(chr(cp) for cp in range(32, 127))
    chars.update(DEFAULT_TEXT)
    for path in paths:
        if not path.exists():
            continue
        source = path.read_text(encoding="utf-8-sig")
        # Match comments and literals together so comment markers inside strings
        # remain valid, while commented-out prose does not bloat the subset.
        pattern = r'//[^\n]*|/\*[\s\S]*?\*/|(?:u8|u|U|L)?"(?:\\.|[^"\\])*"'
        for match in re.finditer(pattern, source):
            token = match.group(0)
            if token.startswith(("//", "/*")):
                continue
            literal = token[token.index('"'):]
            try:
                value = ast.literal_eval(literal)
            except (ValueError, SyntaxError):
                value = literal[1:-1]
            chars.update(c for c in value if c.isprintable())
    return "".join(sorted(chars))


def generate(font_path: Path, sources: list[Path], output: Path, weight: int) -> None:
    chars = source_characters(sources)
    try:
        from fontTools.ttLib import TTFont
        with TTFont(font_path) as font_info:
            cmap = font_info.getBestCmap()
            missing = [c for c in chars if ord(c) not in cmap]
            if missing:
                raise SystemExit("Font is missing characters: " + repr("".join(missing)))
    except ImportError:
        pass
    data = bytearray()
    glyphs = []
    for size in SIZES:
        font = ImageFont.truetype(str(font_path), size)
        try:
            axes = font.get_variation_axes()
            values = [axis["default"] for axis in axes]
            for index, axis in enumerate(axes):
                if axis["name"] == b"Weight":
                    values[index] = max(axis["minimum"], min(weight, axis["maximum"]))
            font.set_variation_by_axes(values)
        except (AttributeError, OSError):
            pass
        for char in chars:
            box = font.getbbox(char, anchor="ls")
            x0, y0, x1, y1 = box
            width, height = x1 - x0, y1 - y0
            offset = len(data)
            if width and height:
                image = Image.new("L", (width, height), 0)
                ImageDraw.Draw(image).text((-x0, -y0), char, font=font, fill=255, anchor="ls")
                alpha = [(pixel + 8) // 17 for pixel in image.getdata()]
                if len(alpha) & 1:
                    alpha.append(0)
                data.extend((alpha[i] << 4) | alpha[i + 1] for i in range(0, len(alpha), 2))
            advance = max(1, round(font.getlength(char)))
            glyphs.append((ord(char), offset, width, height, x0, size + y0, advance))
    if not data:
        raise SystemExit("No font data produced")
    lines = [
        "/* Generated by tools/generate_ui_font.py; do not edit manually. */",
        "/* Notebook UI bitmap subset; derived from Noto Sans SC, weight %d." % weight,
        " * Copyright 2014-2021 Adobe; SIL OFL 1.1. See docs/ui/FONT_LICENSE.txt. */",
        "#include <stddef.h>", "#include <stdint.h>", "",
        "typedef struct {", "    uint32_t codepoint, offset;",
        "    uint8_t width, height;", "    int8_t x_offset, y_offset;",
        "    uint8_t advance;", "} ui_glyph_t;", "",
        "static const uint8_t glyph_alpha[] = {",
    ]
    for offset in range(0, len(data), 24):
        lines.append("    " + ",".join("0x%02x" % byte for byte in data[offset:offset + 24]) + ",")
    lines += ["};", "", "static const ui_glyph_t glyphs[] = {"]
    for cp, offset, width, height, xo, yo, advance in glyphs:
        lines.append("    {0x%04x,%d,%d,%d,%d,%d,%d}," % (cp, offset, width, height, xo, yo, advance))
    lines += ["};", "", "static const int font_sizes[] = {13,16,18,20,24,26};",
              "enum { GLYPHS_PER_SIZE = %d };" % len(chars), "", "static int font_index(int size)", "{",
              "    int selected = 0, distance = 10000;",
              "    for (int i = 0; i < 6; ++i) {",
              "        int delta = font_sizes[i] - size; if (delta < 0) delta = -delta;",
              "        if (delta < distance) { distance = delta; selected = i; }", "    }",
              "    return selected;", "}", "", "int ui_font_line_height(int size)", "{",
              "    return font_sizes[font_index(size)] + (font_sizes[font_index(size)] + 4) / 5;", "}", "",
              "const uint8_t *ui_font_glyph(int size, uint32_t codepoint, int *width,",
              "                              int *height, int *x_offset, int *y_offset, int *advance)", "{",
              "    const int base = font_index(size) * GLYPHS_PER_SIZE;",
              "    int low = 0, high = GLYPHS_PER_SIZE - 1;", "    const ui_glyph_t *glyph = NULL;",
              "    while (low <= high) {", "        const int mid = low + (high - low) / 2;",
              "        const ui_glyph_t *candidate = &glyphs[base + mid];",
              "        if (candidate->codepoint == codepoint) { glyph = candidate; break; }",
              "        if (candidate->codepoint < codepoint) low = mid + 1; else high = mid - 1;", "    }",
              "    if (!glyph) glyph = &glyphs[base + %d];" % chars.index('?'),
              "    *width = glyph->width; *height = glyph->height;",
              "    *x_offset = glyph->x_offset; *y_offset = glyph->y_offset;",
              "    *advance = glyph->advance;", "    return glyph_alpha + glyph->offset;", "}", ""]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    print("%d characters x %d sizes; alpha=%d bytes; %s" % (len(chars), len(SIZES), len(data), output))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=Path(r"C:\Windows\Fonts\NotoSansSC-VF.ttf"))
    parser.add_argument("--source", action="append", type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "main/ui_font_data.c")
    parser.add_argument("--weight", type=int, default=450)
    args = parser.parse_args()
    generate(args.font, args.source or [ROOT / "main/ui_pages.c", ROOT / "main/ui_app.c"], args.output, args.weight)
